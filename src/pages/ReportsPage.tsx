import React, { useState } from 'react';
import type { AppData } from '../types';
import {
  exportAssetsToCSV,
  exportObservationsToCSV,
  exportMaintenanceToCSV,
  exportToJSON,
} from '../lib/storage';
import { screenSite } from '../lib/screening';
import { NoticeBanner } from '../components/NoticeBanner';

interface ReportsPageProps {
  data: AppData;
  isSimulated: boolean;
}

export const ReportsPage: React.FC<ReportsPageProps> = ({ data, isSimulated }) => {
  const { assets, siteAssessments, observations, maintenanceIssues } = data;
  const [reportTitle, setReportTitle] = useState('JalSetu Purulia &bull; Conservation Status Summary');
  const [generatedDate] = useState(new Date().toLocaleDateString('en-IN', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  }));

  const handlePrint = () => {
    window.print();
  };

  const handleExportJSON = () => {
    const json = exportToJSON();
    const blob = new Blob([json], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.setAttribute('href', url);
    link.setAttribute('download', `jalsetu_full_database_${new Date().toISOString().substring(0, 10)}.json`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div>
      <div className="page-header">
        <div>
          <h1>Planning &amp; Audit Reports</h1>
          <p style={{ color: 'var(--color-text-secondary)', fontSize: '0.875rem' }}>
            Generate structured summaries for village committees, block reviews, and student project evaluation.
          </p>
        </div>
        <div className="btn-group">
          <button type="button" className="btn btn-secondary btn-sm" onClick={handleExportJSON}>
            Export Full Database (JSON)
          </button>
          <button type="button" className="btn btn-primary btn-sm" onClick={handlePrint}>
            Print / Save as PDF
          </button>
        </div>
      </div>

      <div className="page-body">
        <NoticeBanner isSimulated={isSimulated} />

        {/* Clear Non-Certification Disclaimer */}
        <div className="notice notice--warning" style={{ marginBottom: '1.5rem' }}>
          <div>
            <strong>Disclaimer on Generated Reports: </strong>
            This document is generated by JalSetu Purulia, an open-source student innovation prototype.
            It reflects user-entered and simulated demonstration records.
            <strong> It is NOT an official technical sanction, government certification, or certified DPR (Detailed Project Report).</strong>
          </div>
        </div>

        {/* Printable Report Document */}
        <div className="card" style={{ padding: '2rem' }}>
          <div style={{ borderBottom: '2px solid var(--color-primary)', paddingBottom: '1rem', marginBottom: '1.5rem' }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'baseline' }}>
              <div>
                <h2 style={{ fontSize: '1.5rem', color: 'var(--color-primary-dark)' }}>{reportTitle}</h2>
                <p style={{ color: 'var(--color-text-secondary)', fontSize: '0.875rem' }}>
                  Target Geography: Purulia District, West Bengal &bull; Generated: {generatedDate}
                </p>
              </div>
              <div style={{ textAlign: 'right' }}>
                <span
                  style={{
                    display: 'inline-block',
                    padding: '3px 8px',
                    borderRadius: '4px',
                    fontSize: '0.75rem',
                    backgroundColor: isSimulated ? '#fcf3cf' : '#d4efdf',
                    color: isSimulated ? '#7d6608' : '#145a32',
                    border: '1px solid currentColor',
                  }}
                >
                  {isSimulated ? 'Demonstration (Simulated Data)' : 'Local User Database'}
                </span>
              </div>
            </div>
          </div>

          {/* Section 1: Executive Summary */}
          <div style={{ marginBottom: '1.5rem' }}>
            <h3 style={{ fontSize: '1.1rem', marginBottom: '0.5rem', borderBottom: '1px solid var(--color-border)', paddingBottom: '0.25rem' }}>
              1. Executive Summary
            </h3>
            <div className="stats-grid" style={{ marginBottom: '1rem' }}>
              <div className="stat-card">
                <div className="stat-label">Total Registered Assets</div>
                <div className="stat-value">{assets.length}</div>
              </div>
              <div className="stat-card">
                <div className="stat-label">Candidate Sites Screened</div>
                <div className="stat-value">{siteAssessments.length}</div>
              </div>
              <div className="stat-card">
                <div className="stat-label">Logged Observations</div>
                <div className="stat-value">{observations.length}</div>
              </div>
              <div className="stat-card">
                <div className="stat-label">Open Maintenance Items</div>
                <div className="stat-value">{maintenanceIssues.filter(m => m.status === 'open').length}</div>
              </div>
            </div>
          </div>

          {/* Section 2: Asset Inventory */}
          <div style={{ marginBottom: '1.5rem' }}>
            <h3 style={{ fontSize: '1.1rem', marginBottom: '0.5rem', borderBottom: '1px solid var(--color-border)', paddingBottom: '0.25rem' }}>
              2. Registered Water Assets ({assets.length})
            </h3>
            {assets.length === 0 ? (
              <p style={{ fontSize: '0.85rem', color: 'var(--color-text-muted)' }}>No assets registered.</p>
            ) : (
              <div className="table-wrap">
                <table>
                  <thead>
                    <tr>
                      <th>Asset Name</th>
                      <th>Type</th>
                      <th>Location</th>
                      <th>Condition</th>
                      <th>Maintenance Status</th>
                      <th>Capacity</th>
                      <th>Responsible Body</th>
                    </tr>
                  </thead>
                  <tbody>
                    {assets.map(a => (
                      <tr key={a.id}>
                        <td><strong>{a.name}</strong></td>
                        <td>{a.type.replace('_', ' ')}</td>
                        <td>{a.block || ''} {a.village ? `(${a.village})` : ''}</td>
                        <td>{a.condition}</td>
                        <td>{a.maintenanceStatus}</td>
                        <td>{a.storageCapacityLitres ? `${a.storageCapacityLitres.toLocaleString()} L` : '—'}</td>
                        <td>{a.responsibleOrg || '—'}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>

          {/* Section 3: Candidate Site Screening */}
          <div style={{ marginBottom: '1.5rem' }}>
            <h3 style={{ fontSize: '1.1rem', marginBottom: '0.5rem', borderBottom: '1px solid var(--color-border)', paddingBottom: '0.25rem' }}>
              3. Candidate Site Screening Results ({siteAssessments.length})
            </h3>
            {siteAssessments.length === 0 ? (
              <p style={{ fontSize: '0.85rem', color: 'var(--color-text-muted)' }}>No candidate sites recorded.</p>
            ) : (
              <div className="table-wrap">
                <table>
                  <thead>
                    <tr>
                      <th>Candidate Site</th>
                      <th>Type</th>
                      <th>Score</th>
                      <th>Recommendation</th>
                      <th>Missing Information</th>
                    </tr>
                  </thead>
                  <tbody>
                    {siteAssessments.map(s => {
                      const res = screenSite(s);
                      return (
                        <tr key={s.id}>
                          <td><strong>{s.name}</strong></td>
                          <td>{s.siteType.replace('_', ' ')}</td>
                          <td>
                            {res.isInsufficient ? (
                              <span style={{ fontWeight: 600, color: '#ad6800' }}>
                                Insufficient Data (Score Deferred)
                              </span>
                            ) : (
                              <span>
                                {res.percentage}% ({res.totalScore}/{res.maxPossibleScore})
                              </span>
                            )}
                          </td>
                          <td style={{ fontSize: '0.8rem' }}>{res.recommendation}</td>
                          <td style={{ fontSize: '0.75rem', color: 'var(--color-text-muted)' }}>
                            {res.missingData.join(', ') || 'None listed'}
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            )}
          </div>

          {/* Section 4: Maintenance Register */}
          <div style={{ marginBottom: '1.5rem' }}>
            <h3 style={{ fontSize: '1.1rem', marginBottom: '0.5rem', borderBottom: '1px solid var(--color-border)', paddingBottom: '0.25rem' }}>
              4. Maintenance &amp; Inspection Issues ({maintenanceIssues.length})
            </h3>
            {maintenanceIssues.length === 0 ? (
              <p style={{ fontSize: '0.85rem', color: 'var(--color-text-muted)' }}>No maintenance issues recorded.</p>
            ) : (
              <div className="table-wrap">
                <table>
                  <thead>
                    <tr>
                      <th>Date</th>
                      <th>Asset</th>
                      <th>Category</th>
                      <th>Priority</th>
                      <th>Status</th>
                      <th>Description</th>
                      <th>Action Taken</th>
                    </tr>
                  </thead>
                  <tbody>
                    {maintenanceIssues.map(m => {
                      const asset = assets.find(a => a.id === m.assetId);
                      return (
                        <tr key={m.id}>
                          <td>{m.dateReported}</td>
                          <td>{asset?.name || m.assetId}</td>
                          <td>{m.category.replace('_', ' ')}</td>
                          <td>{m.priority}</td>
                          <td>{m.status}</td>
                          <td style={{ maxWidth: '240px' }}>{m.description}</td>
                          <td style={{ maxWidth: '200px' }}>{m.actionTaken || '—'}</td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            )}
          </div>

          {/* Report Footer */}
          <div style={{ marginTop: '2rem', paddingTop: '1rem', borderTop: '1px solid var(--color-border)', fontSize: '0.75rem', color: 'var(--color-text-muted)', display: 'flex', justifyContent: 'space-between' }}>
            <span>JalSetu Purulia &bull; Seva First Innovation Challenge Submission</span>
            <span>Local Storage Instance &bull; Open-Source Prototype</span>
          </div>
        </div>
      </div>
    </div>
  );
};
